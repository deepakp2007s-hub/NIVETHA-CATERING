
import logging
import secrets
from datetime import datetime, timedelta, timezone
from typing import Any, Optional

import bcrypt
from fastapi import Depends, HTTPException, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer
from jose import JWTError, jwt

from app.core.config import settings


logger = logging.getLogger("nivetha_catering.security")

bearer_scheme = HTTPBearer(auto_error=False)

JWT_ISSUER = "nivetha-catering-api"
JWT_AUDIENCE = "nivetha-catering-clients"
BCRYPT_ROUNDS = 12
MAX_PASSWORD_BYTES = 72


# ---------------------------------------------------------------------------
# PASSWORD VALIDATION
# ---------------------------------------------------------------------------

def validate_password(password: str) -> bytes:
    if not isinstance(password, str):
        raise ValueError("Password must be a string.")

    if not password or not password.strip():
        raise ValueError("Password cannot be empty.")

    password_bytes = password.encode("utf-8")

    if len(password_bytes) > MAX_PASSWORD_BYTES:
        raise ValueError(
            "Password cannot exceed 72 UTF-8 bytes."
        )

    return password_bytes


# ---------------------------------------------------------------------------
# PASSWORD HASHING
# ---------------------------------------------------------------------------

def hash_password(password: str) -> str:
    password_bytes = validate_password(password)

    salt = bcrypt.gensalt(rounds=BCRYPT_ROUNDS)

    hashed_password = bcrypt.hashpw(
        password_bytes,
        salt,
    )

    return hashed_password.decode("utf-8")


# ---------------------------------------------------------------------------
# PASSWORD VERIFICATION
# ---------------------------------------------------------------------------

def verify_password(
    plain_password: str,
    hashed_password: str,
) -> bool:

    try:
        if not isinstance(hashed_password, str):
            return False

        password_bytes = validate_password(plain_password)

        stored_hash = hashed_password.encode("utf-8")

        if not stored_hash.startswith(
            (b"$2a$", b"$2b$", b"$2y$")
        ):
            return False

        return bcrypt.checkpw(
            password_bytes,
            stored_hash,
        )

    except (ValueError, TypeError, UnicodeError):
        return False


# ---------------------------------------------------------------------------
# CREATE ACCESS TOKEN
# ---------------------------------------------------------------------------

def create_access_token(
    data: Optional[dict[str, Any]] = None,
    subject: Optional[str] = None,
    expires_delta: Optional[timedelta] = None,
) -> str:

    payload = data.copy() if data else {}

    if subject is not None:
        payload["sub"] = str(subject)

    if not payload.get("sub"):
        raise ValueError(
            "JWT subject is required."
        )

    now = datetime.now(timezone.utc)

    expiration = (
        now + expires_delta
        if expires_delta is not None
        else now + timedelta(
            minutes=settings.ACCESS_TOKEN_EXPIRE_MINUTES
        )
    )

    if expiration <= now:
        raise ValueError(
            "Token expiration must be in the future."
        )

    # Prevent caller-provided security claims from overriding
    # the values generated by this function.
    payload.update({
        "iss": JWT_ISSUER,
        "aud": JWT_AUDIENCE,
        "iat": now,
        "nbf": now,
        "exp": expiration,
        "jti": secrets.token_urlsafe(32),
    })

    return jwt.encode(
        payload,
        settings.JWT_SECRET,
        algorithm="HS256",
    )


# ---------------------------------------------------------------------------
# DECODE AND VALIDATE ACCESS TOKEN
# ---------------------------------------------------------------------------

def decode_access_token(
    token: str,
) -> dict[str, Any]:

    if not isinstance(token, str) or not token.strip():
        raise ValueError("Access token is missing.")

    try:
        payload = jwt.decode(
            token,
            settings.JWT_SECRET,
            algorithms=["HS256"],
            issuer=JWT_ISSUER,
            audience=JWT_AUDIENCE,
            options={
                "require_exp": True,
                "require_sub": True,
                "require_iat": True,
                "require_nbf": True,
                "require_iss": True,
                "require_aud": True,
                "require_jti": True,
            },
        )

        if not isinstance(payload, dict):
            raise ValueError("Invalid token payload.")

        subject = payload.get("sub")

        if not isinstance(subject, str) or not subject.strip():
            raise ValueError("Invalid token subject.")

        if not isinstance(payload.get("jti"), str):
            raise ValueError("Invalid token identifier.")

        return payload

    except (JWTError, ValueError, TypeError) as exc:
        # Do not log the token or its contents.
        logger.warning(
            "JWT validation failed: %s",
            type(exc).__name__,
        )

        raise ValueError(
            "Invalid or expired access token."
        ) from exc


# ---------------------------------------------------------------------------
# GET CURRENT USER ID
# ---------------------------------------------------------------------------

def get_current_user_id(
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(
        bearer_scheme
    ),
) -> str:

    if credentials is None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required.",
            headers={
                "WWW-Authenticate": "Bearer",
            },
        )

    if credentials.scheme.lower() != "bearer":
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid authentication scheme.",
            headers={
                "WWW-Authenticate": "Bearer",
            },
        )

    try:
        payload = decode_access_token(
            credentials.credentials
        )

        return payload["sub"]

    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired access token.",
            headers={
                "WWW-Authenticate": "Bearer",
            },
        ) from exc


# ---------------------------------------------------------------------------
# GET CURRENT USER PAYLOAD
# ---------------------------------------------------------------------------

def get_current_token_payload(
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(
        bearer_scheme
    ),
) -> dict[str, Any]:

    if credentials is None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required.",
            headers={
                "WWW-Authenticate": "Bearer",
            },
        )

    try:
        return decode_access_token(
            credentials.credentials
        )

    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or expired access token.",
            headers={
                "WWW-Authenticate": "Bearer",
            },
        ) from exc
